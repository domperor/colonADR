test_that("apcadr_works", {
  data<-read.csv("sample_CF_data.csv")
  x<-apcadr(data$統計_診断)
  expect_equal(as.numeric(format(x$APCstrict, digits = 5)), 0.57576)
  expect_equal(as.numeric(format(x$APCloose, digits = 5)), 0.59596)
  expect_equal(as.numeric(format(x$ADRstrict, digits = 5)), 0.38384)
  expect_equal(as.numeric(format(x$ADRloose, digits = 5)), 0.39394)
  expect_equal(as.numeric(format(x$PPCstrict, digits = 5)), 0.61616)
  expect_equal(as.numeric(format(x$PPCloose, digits = 5)), 0.63636)
  expect_equal(as.numeric(format(x$PDRstrict, digits = 5)), 0.40404)
  expect_equal(as.numeric(format(x$PDRloose, digits = 5)), 0.41414)
})
